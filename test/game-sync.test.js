const test = require('node:test')
const assert = require('node:assert/strict')
const tick = () => new Promise(setImmediate)
async function pair(t, options = {}) {
  const { createGameSync } = await import('../p2p/game-sync.mjs')
  const matchId = 'ab'.repeat(32)
  const sent = []
  let host, guest
  host = createGameSync({ role: 'host', matchId, send: m => { sent.push(m); queueMicrotask(() => guest.receive(m)) }, ...options })
  guest = createGameSync({ role: 'guest', matchId, send: m => queueMicrotask(() => host.receive(m)), ...options })
  t.after(() => { host.close(); guest.close() })
  let id = 0
  const request = (peer, position) => ({ matchId, requestId: ++id, revision: peer.getState().revision, position })
  const move = async (peer, position) => { const result = await peer.requestMove(request(peer, position)); await tick(); assert.deepEqual(host.getState(), guest.getState()); return result }
  host.announce(); await tick()
  return { host, guest, move, request, sent, matchId, createGameSync }
}
test('both peers start empty; valid moves alternate and snapshots agree', async t => {
  const { host, guest, move } = await pair(t)
  assert.deepEqual(host.getState(), guest.getState())
  assert.deepEqual(host.getState().board, Array(9).fill(null))
  assert.equal(host.getState().revision, 0)
  await move(host, 0); await move(guest, 4)
  assert.equal(host.getState().revision, 2)
  assert.equal(host.getState().currentPlayer, 'X')
})
test('out-of-turn, occupied, malformed and stale moves never change state', async t => {
  const { host, guest, move, request } = await pair(t)
  await assert.rejects(guest.requestMove(request(guest, 0)), /turn/)
  await move(host, 0)
  const before = host.getState()
  await assert.rejects(host.requestMove(request(host, 1)), /turn/)
  await assert.rejects(guest.requestMove(request(guest, 0)), /occupied/)
  for (const position of [-1, 9, 0.5, '1', null]) await assert.rejects(guest.requestMove(request(guest, position)), /Invalid/)
  await assert.rejects(guest.requestMove({ ...request(guest, 1), revision: 0 }), /Stale revision/)
  host.receive({ type: 'game-move', request: { matchId: before.matchId } })
  await tick()
  assert.deepEqual(host.getState(), before)
  assert.deepEqual(guest.getState(), before)
})
test('duplicate request replay is idempotent and changed/older IDs are rejected', async t => {
  const { host, guest, move, request } = await pair(t)
  await move(host, 0)
  const proposal = request(guest, 1)
  await guest.requestMove(proposal)
  await guest.requestMove(proposal)
  assert.equal(host.getState().revision, 2)
  await assert.rejects(guest.requestMove({ ...proposal, position: 2 }), /Invalid or stale/)
  await move(host, 3)
  await guest.requestMove(proposal) // A retry after the host advances returns current state.
  assert.equal(guest.getState().revision, 3)
  await move(guest, 4); await move(host, 8)
  await assert.rejects(guest.requestMove(proposal), /Invalid or stale/)
  assert.equal(host.getState().revision, 5)
})
const lines = [[0,1,2],[3,4,5],[6,7,8],[0,3,6],[1,4,7],[2,5,8],[0,4,8],[2,4,6]]
for (const line of lines) test(`synchronized win ${line.join('-')} and post-game rejection`, async t => {
  const { host, guest, move, request } = await pair(t)
  const other = Array.from({ length: 9 }, (_, i) => i).filter(i => !line.includes(i))
  await move(host, line[0]); await move(guest, other[0]); await move(host, line[1]); await move(guest, other[1]); await move(host, line[2])
  assert.equal(host.getState().winner, 'X')
  assert.equal(guest.getState().status, 'won')
  const before = host.getState()
  await assert.rejects(guest.requestMove(request(guest, other[2])), /complete/)
  assert.deepEqual(host.getState(), before)
})
test('guest win is synchronized', async t => {
  const { host, guest, move } = await pair(t)
  for (const [i, p] of [0,3,1,4,8,5].entries()) await move(i % 2 ? guest : host, p)
  assert.equal(host.getState().winner, 'O')
})
test('draw is synchronized through revision nine', async t => {
  const { host, guest, move } = await pair(t)
  for (const [i, p] of [0,1,2,4,3,5,7,6,8].entries()) await move(i % 2 ? guest : host, p)
  assert.equal(host.getState().status, 'draw')
  assert.equal(host.getState().winner, null)
  assert.equal(host.getState().revision, 9)
})
test('stale updates are ignored; conflicting or invalid history is rejected', async t => {
  const { host, guest, move, sent } = await pair(t)
  const initial = sent[0]
  await move(host, 0)
  guest.receive(initial)
  assert.equal(guest.getState().revision, 1)
  assert.throws(() => guest.receive({ ...initial, revision: 1, moves: [1] }), /Conflicting/)
  assert.throws(() => guest.receive({ ...initial, revision: 2, moves: [0,0] }), /occupied/)
  assert.throws(() => guest.receive({ ...initial, revision: 9 }), /Invalid/)
  assert.deepEqual(host.getState(), guest.getState())
})
test('pending requests are bounded, time out, and are rejected on disconnect', async t => {
  const { createGameSync } = await import('../p2p/game-sync.mjs')
  const matchId = 'ab'.repeat(32)
  const guest = createGameSync({ role: 'guest', matchId, send() {}, timeoutMs: 20 })
  t.after(() => guest.close())
  const request = { matchId, requestId: 1, revision: 0, position: 0 }
  const pending = guest.requestMove(request)
  await assert.rejects(guest.requestMove(request), /pending/)
  await assert.rejects(pending, /timed out/)
  const next = guest.requestMove({ ...request, requestId: 2 })
  guest.close()
  await assert.rejects(next, /disconnected/)
  await assert.rejects(guest.requestMove(request), /disconnected/)
  assert.equal(guest.getState(), null)
})
test('old match requests and updates cannot alter a new session', async t => {
  const { host, guest, request, sent } = await pair(t)
  const before = host.getState()
  host.receive({ type: 'game-move', request: { ...request(guest, 0), matchId: 'cd'.repeat(32) } })
  guest.receive({ ...sent[0], matchId: 'cd'.repeat(32), moves: [0], revision: 1 })
  assert.deepEqual(host.getState(), before)
  assert.deepEqual(guest.getState(), before)
  await assert.rejects(host.requestMove({ ...request(host, 0), matchId: 'cd'.repeat(32) }), /Stale match/)
})
